export function useT() {
  const { language } = useSettings();
  const code = LANG_CODE[language] ?? "en";
  const strings = LANGS[code] ?? en;
  const t = (key: TKey) => strings[key] ?? en[key] ?? key;
  return {
    t,
    isRTL: language === "Arabic",
    tCat: (category: string) => {
      const key = CAT_KEY[category];
      return key ? t(key) : category;
    },
  };
}
